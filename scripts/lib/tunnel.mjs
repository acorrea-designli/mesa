// Pure helpers for `pnpm tunnel` (scripts/tunnel.mjs): the Cloudflare Tunnel that publishes Mesa to the phone.
//
// The tunnel is a named cloudflared tunnel whose one ingress rule sends https://<MESA_PUBLIC_URL host> to
// http://127.0.0.1:8790, with a catch-all 404. The hostname must sit behind a Cloudflare Access app (login with
// Andrés's email), so an unauthenticated request never reaches Mesa. `status` PROVES that by probing the public URL
// without credentials: Cloudflare must answer with an Access redirect or block; if Mesa itself answers, the Access
// app is missing or misrouted and everything here refuses (exit 3).

export const MESA_TARGET = "http://127.0.0.1:8790";
export const DEFAULT_TUNNEL = "mesa";
export const WINDOWS_SERVICE = "Cloudflared";

export const tunnelName = (env) => env.MESA_CF_TUNNEL?.trim() || DEFAULT_TUNNEL;

/** MESA_PUBLIC_URL -> its hostname ("mesa.example.com"), or null when unset, not https, or not a real domain. */
export function hostFromPublicUrl(raw) {
  const s = raw?.trim();
  if (!s) return null;
  try {
    const u = new URL(s);
    return u.protocol === "https:" && u.hostname.includes(".") ? u.hostname : null;
  } catch {
    return null;
  }
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`; // YAML single-quoted: no escapes to get wrong on Windows paths

/**
 * The cloudflared config file text. Lives outside the repo (~/.cloudflared); it names the credentials file the
 * tunnel's `create` wrote there, never the credentials themselves.
 */
export function buildConfig({ tunnel, uuid, credentialsFile, hostname }) {
  return [
    "# Generated by `pnpm tunnel` (ops repo). Safe to delete: it is rewritten on `pnpm tunnel up`.",
    `tunnel: ${q(uuid)}`,
    `credentials-file: ${q(credentialsFile)}`,
    "ingress:",
    `  # ${tunnel}: Mesa behind Cloudflare Access`,
    `  - hostname: ${q(hostname)}`,
    `    service: ${MESA_TARGET}`,
    "  - service: http_status:404",
    "",
  ].join("\n");
}

/** `cloudflared tunnel list --output json` -> { id, name, connections } for the live tunnel called `name`, or null. */
export function parseTunnelList(text, name) {
  let list;
  try {
    list = JSON.parse(text);
  } catch {
    return null;
  }
  if (!Array.isArray(list)) return null;
  // cloudflared reports a live tunnel with the zero time "0001-01-01T00:00:00Z" in deleted_at.
  const deleted = (x) => Boolean(x?.deleted_at) && !String(x.deleted_at).startsWith("0001-01-01");
  const t = list.find((x) => x?.name === name && !deleted(x));
  if (!t?.id) return null;
  const conns = Array.isArray(t.connections) ? t.connections.length : 0;
  return { id: t.id, name: t.name, connections: conns };
}

/** `sc query Cloudflared` text -> "running" | "stopped" | "absent" | "other". */
export function parseServiceState(text, exitCode = 0) {
  if (exitCode === 1060 || /1060|does not exist/i.test(text ?? "")) return "absent";
  const m = /STATE\s*:\s*\d+\s+(\w+)/i.exec(text ?? "");
  if (!m) return exitCode === 0 ? "other" : "absent";
  const st = m[1].toUpperCase();
  if (st === "RUNNING") return "running";
  if (st === "STOPPED") return "stopped";
  return "other";
}

/**
 * Classify the unauthenticated probe of https://<host>/ (redirects not followed).
 *  - "access":      Cloudflare Access answered: a redirect to its login (cloudflareaccess.com or /cdn-cgi/access/), or a
 *                   403 that Mesa did not produce. This is the only good answer.
 *  - "mesa":        Mesa answered (its guard header, a Next.js response, or any 2xx). BAD: Access is not in front.
 *  - "unreachable": no answer, or Cloudflare's tunnel/DNS error (502, 530, 1033...): the tunnel is not up yet.
 *  - "unknown":     something else; not proof of anything.
 * `p` = { error?: boolean, status: number, location?: string, headers: { name: value } (lower-case names), body?: string }
 */
export function classifyProbe(p) {
  if (!p || p.error) return "unreachable";
  const h = p.headers ?? {};
  const loc = p.location ?? h.location ?? "";
  if (h["x-mesa-guard"] || /next\.js/i.test(h["x-powered-by"] ?? "")) return "mesa";
  if (p.status >= 300 && p.status < 400) {
    return /cloudflareaccess\.com|\/cdn-cgi\/access\//i.test(loc) ? "access" : "unknown";
  }
  if (p.status >= 200 && p.status < 300) return "mesa";
  if (p.status === 403 && /cloudflare/i.test(h.server ?? "")) return "access";
  if ([502, 503, 504, 521, 522, 523, 524, 530].includes(p.status)) return "unreachable";
  return "unknown";
}

/**
 * State from `collect()` in tunnel.mjs: { installed, hostname, tunnel: {id,connections}|null, service: "running"|..., pid: boolean,
 * probe: "access"|"mesa"|"unreachable"|"unknown"|"skipped" }.
 * Exit 3 when Mesa answers the public URL directly; 0 only when installed, the tunnel is connected and Access is proven in front; else 1.
 */
export function statusExitCode(s) {
  if (s.probe === "mesa") return 3;
  const connected = (s.tunnel?.connections ?? 0) > 0 || s.service === "running" || s.pid === true;
  return s.installed && s.hostname && connected && s.probe === "access" ? 0 : 1;
}

/** One human line per fact, Spanish for the people who read it (Andrés), no secrets. */
export function describe(s) {
  const out = [];
  if (!s.installed) return ["cloudflared no está instalado en esta PC."];
  out.push("cloudflared instalado");
  out.push(
    s.service === "running"
      ? "Servicio de Windows activo"
      : s.service === "stopped"
        ? "Servicio de Windows detenido"
        : s.service === "absent"
          ? "Sin servicio de Windows (el túnel corre como proceso de `pnpm tunnel up`)"
          : "Servicio: estado desconocido",
  );
  if (!s.hostname) out.push("MESA_PUBLIC_URL no está puesta: no hay dirección pública (https://mesa.<dominio>)");
  else out.push(`Dirección: https://${s.hostname}`);
  if (s.tunnel) out.push(`Túnel ${s.tunnel.name ?? "mesa"}: ${s.tunnel.connections} conexión(es) a Cloudflare`);
  else out.push("Túnel no encontrado o sin sesión de Cloudflare (cloudflared tunnel login / create)");
  out.push(
    {
      access: "Prueba sin login: Cloudflare Access responde. Bien.",
      mesa: "MESA RESPONDE SIN ACCESS: la dirección pública llega directo a Mesa. Falta la app de Access. No abras el túnel.",
      unreachable: "Prueba sin login: la dirección no responde todavía (túnel apagado o sin ruta DNS).",
      unknown: "Prueba sin login: respuesta que no es de Access ni de Mesa; no está comprobado.",
      skipped: "Prueba sin login: no se hizo (falta la dirección pública).",
    }[s.probe] ?? "Prueba sin login: sin resultado",
  );
  return out;
}
